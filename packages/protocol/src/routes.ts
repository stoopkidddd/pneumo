export const ERROR_STATUS = {
  bad_request: 400,
  unauthorized: 401,
  forbidden: 403,
  not_found: 404,
  conflict: 409,
  not_initialized: 409,
  gone: 410,
  payload_too_large: 413,
  rate_limited: 429,
  internal: 500,
} as const satisfies Record<ErrorCode, number>;

export type Route = {
  readonly name: string;
  readonly method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  readonly path: string;
  readonly auth: "none" | "bearer" | "setupToken" | "pairCode";
  readonly request?: z.ZodType | "bytes";
  readonly query?: z.ZodType;
  readonly response: z.ZodType | "bytes" | "websocket" | null;
  readonly success: readonly number[];
  readonly errors: readonly ErrorCode[];
  readonly frames?: { readonly client: typeof ClientFrame; readonly server: typeof ServerFrame };
};

